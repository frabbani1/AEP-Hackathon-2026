#!/usr/bin/env python3
"""Measure the peak wind gust of each past storm and write backend/concierge/weather/anchors.json.

    python scripts/calibrate_weather.py                       # reads data/serving/risk/calibration.json + hex_context
    python scripts/calibrate_weather.py --calibration X --hex-context Y

For each storm window in calibration.json it asks the Open-Meteo archive (reanalysis) for hourly wind gusts at the
service-area centre and keeps the highest one. The first storm maps to the "sep-2024-like" preset and the last to
"feb-2025-like", the same way risk/calibrate.py builds the presets. Only a rounded area-centre coordinate is sent.

Run it again after any ETL run that changes the storm windows. Review the diff before committing.
"""
from __future__ import annotations

import argparse
import json
import sys
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from concierge.weather.openmeteo import ARCHIVE_URL, snap  # noqa: E402
from concierge.weather.severity import ANCHORS_FILE  # noqa: E402


def area_centre(hex_context: Path) -> tuple[float, float]:
    import pyarrow.parquet as pq
    rows = pq.read_table(hex_context).to_pylist()
    total = sum(r["n_premises"] for r in rows)
    return (sum(r["center_lat"] * r["n_premises"] for r in rows) / total,
            sum(r["center_lon"] * r["n_premises"] for r in rows) / total)


def peak_gust(lat: float, lon: float, start: str, end: str) -> tuple[float, str]:
    q = {"latitude": f"{lat:.2f}", "longitude": f"{lon:.2f}", "start_date": start, "end_date": end,
         "hourly": "wind_gusts_10m", "wind_speed_unit": "mph", "timezone": "GMT"}
    with urllib.request.urlopen(f"{ARCHIVE_URL}?{urllib.parse.urlencode(q)}", timeout=30) as r:  # noqa: S310
        hourly = json.load(r)["hourly"]
    best = max(((g, t) for g, t in zip(hourly["wind_gusts_10m"], hourly["time"]) if g is not None))
    return best


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--calibration", default=str(ROOT / "data/serving/risk/calibration.json"))
    ap.add_argument("--hex-context", default=str(ROOT / "data/curated/tables/hex_context.parquet"))
    ap.add_argument("--out", default=str(ANCHORS_FILE))
    args = ap.parse_args()

    cal = json.loads(Path(args.calibration).read_text())
    storms = cal["storms"]
    if len(storms) != 2:
        raise SystemExit(f"expected 2 storms in calibration.json, found {len(storms)}")
    lat, lon = (snap(v) for v in area_centre(Path(args.hex_context)))
    out_storms = []
    for storm, preset in zip(storms, ("sep-2024-like", "feb-2025-like")):
        gust, when = peak_gust(lat, lon, storm["start"], storm["end"])
        out_storms.append({"label": storm["label"], "preset": preset, "start": storm["start"], "end": storm["end"],
                           "peak_gust_mph": round(gust, 1), "peak_gust_time": when,
                           "multiplier": round(cal["presets"][preset], 3)})
        print(f"{storm['label']}: peak gust {gust:.1f} mph at {when} UTC -> multiplier {cal['presets'][preset]:.3f}")
    doc = {
        "about": "Peak wind gust of each storm in the damage data, used to place a forecast on the storm-strength scale. "
                 "Generated by scripts/calibrate_weather.py. Multipliers here are for reference; the API reads the "
                 "engine's own presets.",
        "source": "Open-Meteo archive (reanalysis), hourly wind_gusts_10m, mph, UTC",
        "point": {"grid_lat": lat, "grid_lon": lon, "note": "centre of the service area, rounded to 0.05 degrees"},
        "config_hash": cal["config_hash"],
        "generated": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        "storms": out_storms,
    }
    Path(args.out).write_text(json.dumps(doc, indent=2) + "\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
